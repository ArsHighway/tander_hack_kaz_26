_LOOKUP = {alias.casefold(): canon for canon, aliases in _UNITS.items() for alias in aliases}
_LOOKUP.update({canon.casefold(): canon for canon in _UNITS})
# Приставки м и М различаются только регистром: «мВт» — милливатт, «МВт» — мегаватт (10⁹ разницы).
# Такие обозначения сверяются как написаны; строчными («мвт») — неизвестно что, не пересчитываем.
_EXACT = {"мВт": "мВт", "МВт": "МВт", "Мвт": "МВт", "MW": "МВт", "mW": "мВт", "Н": "Н"}
AMBIGUOUS_SYMBOLS = {"мвт", "mw"}
# Строчное «н» — не ньютон (слишком частая буква): только «Н» как написано и «ньютон».
for _ambiguous in AMBIGUOUS_SYMBOLS | {"н"}:
    _LOOKUP.pop(_ambiguous, None)
# «градус» без уточнения — угол или температура: у характеристики с ° или °C это её единица
# (`values._fit_quantitative`), в справочнике решает имя (`portal.standards.canon_unit`).
DEGREE_WORDS = frozenset({"градус", "градусов", "градусы", "град", "град.", "градуса"})


def normalize_unit(text: str | None) -> str | None:
    """Каноническая единица или None, если это не похоже на единицу измерения."""
    if not text:
        return None
    if (exact := _EXACT.get(text.strip().rstrip("."))) is not None:
        return exact
    key = re.sub(r"\s+", " ", text.strip()).casefold()
    found = _LOOKUP.get(key) or _LOOKUP.get(key.rstrip("."))
    if found is None and ";" in key:
        # «Мегаватт; тысяча киловатт» (КТРУ) — единица по любой части.
        parts = (normalize_unit(part) for part in key.split(";"))
        return next((u for u in parts if u), None)
    if found is None and "(" in key:
        # «миллиампер (ма)» в стандартах портала: название и обозначение — подходит любое.
        outer, _, inner = key.partition("(")
        word = normalize_unit(outer)
        if inner.rstrip(") ").strip() in AMBIGUOUS_SYMBOLS:
            # «милливатт (мвт)» — милли; «мегаватт (мвт)» у лазера — слово и обозначение спорят.
            return word if word == "мВт" else None
        return word or normalize_unit(inner.rstrip(")"))
    if found or key.count("/") != 1:
        return found
    # Составная единица по частям: «гр/м2», «гр./кв.м» — «г/м2», если такая единица есть.
    top, bottom = (normalize_unit(part) for part in key.split("/"))
    return _LOOKUP.get(f"{top}/{bottom}".casefold()) if top and bottom else None


