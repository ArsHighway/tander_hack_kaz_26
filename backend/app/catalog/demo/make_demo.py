def main() -> None:
    out = {"version": "synthetic-demo-2026-10-01", "source": "synthetic", "positions": POSITIONS}
    path = HERE / "demo.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    chars = [c for p in POSITIONS for c in p["characteristics"]]
    with_list = sum(1 for c in chars if c.get("values") or c.get("range"))
    print(
        f"позиций {len(POSITIONS)}, характеристик {len(chars)}, "
        f"с перечнем или диапазоном {with_list}"
    )


if __name__ == "__main__":
    main()
