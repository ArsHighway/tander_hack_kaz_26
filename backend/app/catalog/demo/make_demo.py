def q(name, values, required=True, **kw):
    return {"name": name, "kind": "qualitative", "values": values, "required": required, **kw}


def n(name, unit, values=None, rng=None, required=True, **kw):
    spec = {"name": name, "kind": "quantitative", "unit": unit, "required": required, **kw}
    if values is not None:
        spec["values"] = values
    if rng is not None:
        spec["range"] = {"min": rng[0], "max": rng[1]}
    return spec


