"""Три категории хакатона и коды ОКПД2, по которым в КТРУ выбираются их позиции.

Ссылки КТРУ на КПГЗ портала нет (в `NSI/classifiers` позиции — только ОКПД2, НКМИ и ТСР), поэтому
граница категории — явный список префиксов ОКПД2 ниже. Префикс с точкой на конце — вся группа
(«25.73.» не зацепит «25.730»), без точки — полный код ОКПД2 из 12 знаков.

Как выбраны границы (09.10.2026, по 60 087 действующим позициям КТРУ и наименованиям СТЕ из
`Инструменты.xlsx`, 99 998 строк):

- одежда — раздел 14 целиком (879 действующих позиций). КПГЗ портала «Одежда» шире (обувь, сумки,
  кошельки — ОКПД2 раздела 15), но задание называет одежду, а не галантерею.
- мебель — раздел 31 целиком (355).
- инструменты — группы, где в названиях позиций стоят слова инструментов (молоток, пассатижи,
  струбцина, пила, топор, дрель, шуруповёрт, шлифмашина): 25.73 «Инструмент» и 28.24 «Инструменты
  ручные с механизированным приводом» (252 позиции). Плюс измерительный инструмент (штангенциркуль,
  микрометр, угольник, рулетка, линейка) 26.51.33 (33) и мультиметры 26.51.43.110 (3).
  Не взяты: 32.50 (медицинские изделия — «сверло» там стоматологическое), 25.71.11.120 (ножницы
  канцелярские и портновские), 25.99 (степлеры и скобы — канцелярия), 28.99 (дорожные фрезы,
  станки), 32.99 (учебные пособия), прочий 26.51 (лабораторные приборы).
"""

import re

CATEGORIES: dict[str, tuple[str, ...]] = {
    "одежда": ("14.",),
    "мебель": ("31.",),
    "инструменты": ("25.73.", "28.24.", "26.51.33.", "26.51.43.110"),
}


_SERVICE = re.compile(r"^\s*(услуг[аи]|работ[аы])\b", re.IGNORECASE)


def is_service(name: str) -> bool:
    """«Услуги по производству верхней одежды» — позиция КТРУ о работе, а не о товаре.

    В группах `.9` ОКПД2 (14.11.9, 31.09.9, 25.73.9, …) у каждой по две такие позиции без
    характеристик (29 из 1 273 на 09.10.2026). Для подбора товара они только мешают: «верхняя
    одежда» совпала бы с услугой по её пошиву."""
    return _SERVICE.match(name) is not None


def category_of(okpd2: str) -> str | None:
    """Категория хакатона для кода ОКПД2 позиции; не из списка — None."""
    for category, prefixes in CATEGORIES.items():
        if okpd2.startswith(prefixes):
            return category
    return None


def okpd2_prefixes() -> tuple[str, ...]:
    """Все префиксы трёх категорий — для фильтра при чтении XML."""
    return tuple(prefix for prefixes in CATEGORIES.values() for prefix in prefixes)
