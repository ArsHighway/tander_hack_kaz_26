@pytest.mark.parametrize("case", ALL_CARDS)
def test_offered_fix_does_not_lead_to_a_new_block(
    case: tuple[Position, str, str, str, str],
) -> None:
    # Аудит: «Канцелярские» → fix «Овальные» → «противоречит наименованию» → fix «Канцелярские»…
    position, name, description, char, value = case
    for issue in _issues(position, name, description, char, value):
        if issue.fix is None or issue.fix.value is None:
            continue
        after = _issues(position, name, description, char, issue.fix.value)
        assert [i.message for i in after if i.severity == "block"] == []


