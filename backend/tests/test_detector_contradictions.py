def _spec(name: str, values: list[str]) -> CharacteristicSpec:
    return CharacteristicSpec(name=name, kind="qualitative", values=values)


def _position(category: str, *specs: CharacteristicSpec) -> Position:
    return Position(code="T-9", name=category, okpd2="", source="test", characteristics=list(specs))


def _issues(position: Position, name: str, description: str, char: str, value: str) -> list[Issue]:
    card = CardIn(
        name=name, description=description, characteristics=[CharIn(name=char, value=value)]
    )
    return [i for i in detect(card, position) if i.field == f"characteristics.{char}"]


