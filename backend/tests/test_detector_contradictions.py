def test_name_and_description_disagreeing_is_a_hint_not_a_block() -> None:
    # D38: «5W-30» в наименовании, «класс вязкости SAE 10W-40» в описании — текст расходится сам
    # с собой; поле как в наименовании — подсказка без исправления.
    found = _issues(
        _position("Масла моторные", SAE),
        "Масло моторное G-Energy Synthetic Active 5W-30, 4 л",
        "Синтетическое, класс вязкости SAE 10W-40, канистра 4 л.",
        "Класс вязкости",
        "5W-30",
    )
    assert [(i.severity, i.fix) for i in found] == [("warn", None)]
    assert "10w-40" in found[0].message


