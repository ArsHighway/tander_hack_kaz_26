def test_label_of_another_characteristic_is_not_a_block() -> None:
    # Живая СТЕ: «Вид материала каркаса: ЛДСП» в описании — не метка «Вида материала ножек/опор».
    position = _position(
        "Столы", _spec("Вид материала ножек/опор", ["Пластик", "ЛДСП", "Металл"])
    )  # fmt: skip
    found = _issues(
        position, "Стол письменный", "Вид материала каркаса: ЛДСП.", "Вид материала ножек/опор",
        "Пластик",
    )  # fmt: skip
    # явная метка другой характеристики — и не подсказка: warn убирает заявку из
    # «чистых» у модератора.
    assert [i.message for i in found] == []


