def test_nitrile_name_against_latex_field_blocks_with_the_name_value() -> None:
    found = _issues(GLOVES, "Перчатки смотровые нитриловые, размер M", "", "Материал", "Латекс")
    assert [(i.kind, i.severity, i.fix.value if i.fix else None) for i in found] == [
        ("mismatch", "block", "Нитрил")
    ]
    assert "нитрил" in found[0].why


